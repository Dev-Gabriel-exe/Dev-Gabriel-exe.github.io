const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
 const page=await browser.newPage({acceptDownloads:true,viewport:{width:1380,height:900}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const base='http://127.0.0.1:8899/pit-game-jam/';
 await page.goto(base,{waitUntil:'networkidle'});
 await page.locator('.resource-card').first().waitFor();
 assert.equal(await page.locator('.resource-card').count(),28,'all resources');
 await page.locator('button[data-filter="mapa"]').click();
 assert.equal(await page.locator('.resource-card').count(),5,'map filter');
 await page.locator('#assetSearch').fill('floresta');
 assert.equal(await page.locator('.resource-card').count(),1,'search within map');
 await page.locator('#assetSearch').fill('');
 await page.locator('button[data-filter="personagem"]').click();
 assert.equal(await page.locator('.resource-card').count(),6,'character filter');
 const png=await Promise.all([page.waitForEvent('download'),page.locator('.resource-card .download').first().click()]);
 assert(png[0].suggestedFilename().endsWith('.png'),'png download');
 await page.locator('button[data-filter="modelo"]').click();
 assert.equal(await page.locator('.resource-card').count(),5,'glb filter');
 const dl=await Promise.all([page.waitForEvent('download'),page.locator('.resource-card .download').first().click()]);
 assert(dl[0].suggestedFilename().endsWith('.glb'),'glb download');
 console.log('PASS: resource filtering, searching, PNG and GLB browser downloads');
 const studentId='00000000-0000-4000-8000-000000000001',token='a'.repeat(64);
 const messages=[];
 await page.route('https://pit-game-jam-chat.vercel.app/api/chat**',async route=>{
  const r=route.request(),u=new URL(r.url()),action=u.searchParams.get('action'),data=r.postDataJSON()||{};
  let body={ok:true};
  if(action==='health')body={ok:true,chat:true};
  if(action==='join')body={ok:true,studentId,name:data.name,token,code:'PITGAME26'};
  if(action==='messages')body={ok:true,messages};
  if(action==='send'){messages.push({id:messages.length+1,author:r.headers()['x-pit-teacher-pin']?'teacher':'student',mission:data.mission||2,body:data.body,created_at:new Date().toISOString()});body={ok:true,id:messages.length}}
  if(action==='threads')body={ok:true,threads:[{id:studentId,display_name:'Aluno Teste',unread:1,last_body:'Dúvida no jogo'}]};
  if(action==='teacher-login')body={ok:true,room:'PITGAME26'};
  await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify(body)});
 });
 await page.goto(base+'aluno.html',{waitUntil:'domcontentloaded'});
 await page.locator('#pit-quest-deck').waitFor();
 assert.equal(await page.locator('.pitq-rail button').count(),6);
 await page.locator('.pitq-rail button[data-qmission="2"]').click();
 await page.locator('.pitq-route button[data-qroute="3d"]').click();
 assert((await page.locator('.pitq-steps').innerText()).includes('3D'),'3D mission route');
 await page.locator('#pit-chat-root .pitc-fab').click();
 await page.locator('#pit-chat-root input[type="text"]').first().fill('Aluno Teste');
 await page.locator('#pit-chat-root .pitc-primary').click();
 await page.locator('#pit-chat-root textarea').fill('Como importo meu GLB no GDevelop?');
 await page.locator('#pit-chat-root .pitc-primary').click();
 await page.getByText('Como importo meu GLB no GDevelop?').first().waitFor();
 assert.equal(messages.length,1);
 console.log('PASS: 6 missions, 3D practical route, student chat login/send UI');
 await page.goto(base+'professor.html',{waitUntil:'domcontentloaded'});
 await page.locator('#pit-quest-deck').waitFor();
 assert.equal(await page.locator('.pitq-rail button').count(),6);
 await page.locator('#pit-chat-root .pitc-fab').click();
 await page.locator('#pit-chat-root input[type="password"]').fill('test-pin-only');
 await page.locator('#pit-chat-root .pitc-primary').click();
 await page.locator('#pit-chat-root .pitc-thread').first().click();
 await page.locator('#pit-chat-root textarea').fill('Acesse Objects, Add object, 3D Model e selecione seu GLB.');
 await page.locator('#pit-chat-root .pitc-primary').click();
 assert.equal(messages.length,2);
 console.log('PASS: professor inbox, individual reply UI');
 assert.equal(errors.length,0,'browser JS errors: '+errors.join('; '));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
